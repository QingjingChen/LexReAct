#!/usr/bin/env python3
"""Extract the distributable rule layer from the full two-layer LegalRuleML file.

kb/civil_graph.lrml (built by graph2lrml.py from the knowledge graph, not distributed) holds the graph's node texts
in its structural layer. This script keeps only what the reasoner needs: every Constitutive / Prescriptive statement
(hand-written rules and the automatically extracted is-a rules), the override statements, and the legal sources /
associations they reference. It writes kb/civil_rules.lrml and validates it against the OASIS XSD.

  python3 src/extract_rule_layer.py            # kb/civil_graph.lrml -> kb/civil_rules.lrml
"""
import argparse
import copy
import sys
from pathlib import Path

from lxml import etree

sys.path.insert(0, str(Path(__file__).resolve().parent))
from paths import LRML_FULL, LRML_RULES, SCHEMA  # noqa: E402

NS = {'lrml': 'http://docs.oasis-open.org/legalruleml/ns/v1.0/', 'ruleml': 'http://ruleml.org/spec'}
L = '{%s}' % NS['lrml']
RULE_TAGS = {L + 'ConstitutiveStatement', L + 'PrescriptiveStatement'}


def extract(src, dst):
    tree = etree.parse(str(src))
    root = tree.getroot()
    rules = [e for e in root.iter() if e.tag in RULE_TAGS]
    keys = {k for r in rules for e in r.iter() for k in [e.get('key')] if k}
    keys |= {k.lstrip(':') for k in list(keys)}

    out = etree.Element(root.tag, nsmap=root.nsmap)
    for a, v in root.attrib.items():
        out.set(a, v)
    out.append(etree.Comment(' Rule layer of the civil-law LegalRuleML encoding (structural layer removed; '
                             'generated by src/extract_rule_layer.py). '))
    assocs = [a for a in root.find(L + 'Associations')
              if a.tag == L + 'Association'
              and any(t.get('keyref', '').lstrip('#') in keys for t in a.findall(L + 'toTarget'))]
    used_src = {s.get('keyref', '').lstrip('#') for a in assocs for s in a.findall(L + 'appliesSource')}

    for child in root:
        tag = child.tag
        if tag == L + 'LegalSources':
            ls = etree.SubElement(out, tag, attrib=dict(child.attrib))
            for s in child:
                if s.tag != L + 'LegalSource' or s.get('key') in used_src:
                    ls.append(copy.deepcopy(s))
        elif tag == L + 'Associations':
            asc = etree.SubElement(out, tag, attrib=dict(child.attrib))
            for a in assocs:
                asc.append(copy.deepcopy(a))
        elif tag == L + 'Statements' and child.get('key') == 'priorities':
            pass  # appended after the rules
        elif tag == L + 'Statements':
            continue
        elif isinstance(tag, str):
            out.append(copy.deepcopy(child))
    st = etree.SubElement(out, L + 'Statements', key='rules')
    etree.SubElement(st, L + 'Comment').text = 'Rule layer: hand-formalised defeasible rules and is-a rules, flattened.'
    for r in rules:
        st.append(copy.deepcopy(r))
    out.append(copy.deepcopy(root.find(f"{L}Statements[@key='priorities']")))
    etree.ElementTree(out).write(str(dst), encoding='utf-8', xml_declaration=True, pretty_print=True)

    schema = etree.XMLSchema(etree.parse(str(SCHEMA)))
    ok = schema.validate(etree.parse(str(dst)))
    n_tax = sum(r.get('key', '').startswith('tx-') for r in rules)
    print(f'{dst.name}: {len(rules) - n_tax} rules + {n_tax} is-a rules, {len(assocs)} associations, '
          f'{len(used_src)} legal sources; XSD {"valid" if ok else "INVALID"}')
    for e in list(schema.error_log)[:10]:
        print('  ', e.line, e.message[:200])
    return ok


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', default=str(LRML_FULL))
    ap.add_argument('--out', default=str(LRML_RULES))
    a = ap.parse_args()
    sys.exit(0 if extract(Path(a.src), Path(a.out)) else 1)
